// Generates lib/design/tokens.g.dart from docs/design/tokens.json.
//
//   dart run tool/gen_tokens.dart
//
// The output is the `YumdoorTokens` ThemeExtension with a `light` and a `dark`
// instance: colors, text styles, spacing, radii, sizes and shadows. Token names
// become camelCase fields (`surface-sunken` → `surfaceSunken`), each token's
// `usage` becomes its doc comment. Values that are the same in every theme are
// plain strings in tokens.json; themed values are `{"light": …, "dark": …}`;
// `{name}` refers to another token of the same group.
//
// The output is formatted, so running the tool twice produces no diff, and a
// test fails if the committed file is out of date.

import 'dart:convert';
import 'dart:io';

import 'package:dart_style/dart_style.dart';
import 'package:pub_semver/pub_semver.dart';

const _usage = 'Usage: dart run tool/gen_tokens.dart';

void main(List<String> args) {
  if (args.isNotEmpty) {
    stderr.writeln(_usage);
    exitCode = 64;
    return;
  }
  final root = File.fromUri(Platform.script).parent.parent.path;
  final source = File('$root/$tokensJsonPath');
  final output = File('$root/$tokensDartPath');
  try {
    final json = jsonDecode(source.readAsStringSync()) as Map<String, dynamic>;
    output.writeAsStringSync(generateTokens(json));
  } on FormatException catch (e) {
    stderr.writeln('gen_tokens: ${source.path}: ${e.message}');
    exitCode = 1;
    return;
  }
  stdout.writeln('Wrote ${output.path}');
}

const tokensJsonPath = 'docs/design/tokens.json';
const tokensDartPath = 'lib/design/tokens.g.dart';

/// The formatted Dart source of `tokens.g.dart` for the decoded tokens.json.
///
/// Throws a [FormatException] for values it cannot convert.
String generateTokens(Map<String, dynamic> json) {
  final themes = [
    for (final theme in _list(_map(json, 'color'), 'themes'))
      (theme as Map<String, dynamic>)['id'] as String,
  ];
  // Getter name → the group's fields, in file order.
  final groups = {
    'colors': _colors(json, themes).toList(),
    'textStyles': _textStyles(json).toList(),
    'spacing': _lengths(json, 'spacing').toList(),
    'radii': _lengths(json, 'radius').toList(),
    'sizes': _lengths(json, 'size').toList(),
    'shadows': _shadows(json, themes).toList(),
  };
  final fields = [for (final group in groups.values) ...group];

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from $tokensJsonPath.')
    ..writeln('// Do not edit; change the JSON and re-run the tool.')
    ..writeln()
    ..writeln("import 'dart:ui' show lerpDouble;")
    ..writeln()
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln()
    ..writeln('/// Design tokens of ${json['name']}, one instance per theme.')
    ..writeln('/// Widgets read them with `context.tokens`, never literals.')
    ..writeln('@immutable')
    ..writeln('class YumdoorTokens extends ThemeExtension<YumdoorTokens> {')
    ..writeln('  const YumdoorTokens({')
    ..writeAll([for (final f in fields) 'required this.${f.name},'], '\n')
    ..writeln('});')
    ..writeln();
  for (final theme in themes) {
    out
      ..writeln('static const $theme = YumdoorTokens(')
      ..writeAll([
        for (final f in fields)
          '${f.name}: ${f.values[theme] ?? f.values['']},',
      ], '\n')
      ..writeln(');')
      ..writeln();
  }
  for (final f in fields) {
    out
      ..writeln('/// ${f.usage}')
      ..writeln('final ${f.type} ${f.name};')
      ..writeln();
  }
  for (final MapEntry(key: getter, value: group) in groups.entries) {
    if (group.isEmpty) continue;
    out
      ..writeln('/// The $getter by field name, e.g. for the token gallery.')
      ..writeln('Map<String, ${group.first.type}> get $getter => {')
      ..writeAll([for (final f in group) "'${f.name}': ${f.name},"], '\n')
      ..writeln('};')
      ..writeln();
  }
  out
    ..writeln('@override')
    ..writeln('YumdoorTokens copyWith({')
    ..writeAll([for (final f in fields) '${f.type}? ${f.name},'], '\n')
    ..writeln('}) {')
    ..writeln('return YumdoorTokens(')
    ..writeAll([
      for (final f in fields) '${f.name}: ${f.name} ?? this.${f.name},',
    ], '\n')
    ..writeln(');')
    ..writeln('}')
    ..writeln()
    ..writeln('@override')
    ..writeln('YumdoorTokens lerp(YumdoorTokens? other, double t) {')
    ..writeln('if (other == null) return this;')
    ..writeln('return YumdoorTokens(')
    ..writeAll([
      for (final f in fields)
        '${f.name}: ${f.lerp}(${f.name}, other.${f.name}, t)!,',
    ], '\n')
    ..writeln(');')
    ..writeln('}')
    ..writeln('}');

  return DartFormatter(languageVersion: Version(3, 13, 0))
      .format(out.toString());
}

class _Field {
  _Field(this.name, this.type, this.lerp, this.usage, this.values);

  final String name;
  final String type;

  /// Static lerp function for the type, e.g. `Color.lerp`.
  final String lerp;
  final String usage;

  /// Dart expression per theme id; key `''` for theme-independent values.
  final Map<String, String> values;
}

Iterable<_Field> _colors(Map<String, dynamic> json, List<String> themes) {
  final tokens = _tokens(_map(json, 'color'));
  return [
    for (final MapEntry(key: name, value: token) in tokens.entries)
      _Field(_camel(name), 'Color', 'Color.lerp', token['usage'] as String, {
        for (final theme in themes) theme: _color(_themed(tokens, name, theme)),
      }),
  ];
}

Iterable<_Field> _textStyles(Map<String, dynamic> json) {
  final type = _map(json, 'type');
  final families = _map(type, 'families');
  return [
    for (final group in _list(type, 'groups'))
      for (final style in _list(group as Map<String, dynamic>, 'styles'))
        _textStyle(
          style as Map<String, dynamic>,
          family:
              families[group['family']] as String? ??
              (throw FormatException('unknown family ${group['family']}')),
        ),
  ];
}

_Field _textStyle(Map<String, dynamic> style, {required String family}) {
  final name = style['name'] as String;
  final size = _px(style['fontSize']);
  final lineHeight = _px(style['lineHeight']);
  final weight = style['fontWeight'] as int;
  if (weight % 100 != 0 || weight < 100 || weight > 900) {
    throw FormatException('$name: fontWeight $weight is not 100…900');
  }
  final letterSpacing = style['letterSpacing'] as String?;
  // The first family is the bundled font; CSS fallbacks have no meaning here.
  final args = [
    "fontFamily: '${family.split(',').first.trim()}'",
    'fontSize: $size',
    'height: $lineHeight / $size',
    'leadingDistribution: TextLeadingDistribution.even',
    'fontWeight: FontWeight.w$weight',
    if (letterSpacing != null) 'letterSpacing: ${_em(letterSpacing)} * $size',
  ];
  return _Field(
    _camel(name),
    'TextStyle',
    'TextStyle.lerp',
    style['usage'] as String,
    {'': 'TextStyle(${args.join(', ')})'},
  );
}

Iterable<_Field> _lengths(Map<String, dynamic> json, String group) => [
  for (final token in _list(_map(json, group), 'tokens'))
    _Field(
      _camel((token as Map<String, dynamic>)['name'] as String),
      'double',
      'lerpDouble',
      token['usage'] as String,
      {'': _px(token['value'])},
    ),
];

Iterable<_Field> _shadows(Map<String, dynamic> json, List<String> themes) {
  final tokens = _tokens(_map(json, 'shadow'));
  return [
    for (final MapEntry(key: name, value: token) in tokens.entries)
      _Field(
        _camel(name),
        'List<BoxShadow>',
        'BoxShadow.lerpList',
        token['usage'] as String,
        {
          for (final theme in themes)
            theme: _boxShadows(_themed(tokens, name, theme)),
        },
      ),
  ];
}

/// The tokens of a group by name, in file order.
Map<String, Map<String, dynamic>> _tokens(Map<String, dynamic> group) => {
  for (final token in _list(group, 'tokens'))
    (token as Map<String, dynamic>)['name'] as String: token,
};

/// The raw value of token [name] in [theme], with `{other}` references
/// resolved within the same group.
String _themed(
  Map<String, Map<String, dynamic>> tokens,
  String name,
  String theme, [
  Set<String> seen = const {},
]) {
  if (seen.contains(name)) throw FormatException('circular reference: $name');
  final token = tokens[name] ?? (throw FormatException('unknown token $name'));
  final value = switch (token['value']) {
    final String plain => plain,
    final Map<String, dynamic> perTheme =>
      perTheme[theme] as String? ??
          (throw FormatException('$name has no value for theme $theme')),
    final other => throw FormatException('$name: unsupported value $other'),
  };
  final reference = RegExp(r'^\{([\w-]+)\}$').firstMatch(value);
  if (reference == null) return value;
  return _themed(tokens, reference.group(1)!, theme, {...seen, name});
}

String _color(String css) {
  final hex = RegExp(r'^#([0-9a-fA-F]{6})$').firstMatch(css);
  if (hex != null) return 'Color(0xFF${hex.group(1)!.toUpperCase()})';
  final rgba = RegExp(
    r'^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$',
  ).firstMatch(css);
  if (rgba != null) {
    return 'Color.fromRGBO(${rgba.group(1)}, ${rgba.group(2)}, '
        '${rgba.group(3)}, ${rgba.group(4)})';
  }
  throw FormatException('unsupported color "$css" (use #rrggbb or rgba())');
}

/// CSS `box-shadow` (`x y blur [spread] color`, comma-separated layers) as a
/// `List<BoxShadow>` literal.
String _boxShadows(String css) {
  final layers = css.split(RegExp(r',(?![^(]*\))'));
  return '[${layers.map(_boxShadow).join(', ')}]';
}

String _boxShadow(String layer) {
  const length = r'(-?[\d.]+(?:px)?)';
  final match = RegExp(
    '^\\s*$length\\s+$length\\s+$length(?:\\s+$length)?\\s+(\\S.*\\S)\\s*\$',
  ).firstMatch(layer);
  if (match == null) throw FormatException('unsupported shadow "$layer"');
  final spread = match.group(4);
  return 'BoxShadow('
      'offset: Offset(${_px(match.group(1))}, ${_px(match.group(2))}), '
      'blurRadius: ${_px(match.group(3))}, '
      '${spread == null ? '' : 'spreadRadius: ${_px(spread)}, '}'
      'color: ${_color(match.group(5)!)})';
}

/// `"28px"` or `0` as a Dart number literal.
String _px(Object? value) {
  final match = RegExp(r'^(-?\d+(?:\.\d+)?)(?:px)?$').firstMatch('$value');
  if (match == null) throw FormatException('expected a px length, got $value');
  return match.group(1)!;
}

String _em(String value) {
  final match = RegExp(r'^(-?\d*\.?\d+)em$').firstMatch(value);
  if (match == null) throw FormatException('expected an em length, got $value');
  return match.group(1)!;
}

/// `surface-sunken` → `surfaceSunken`, `space-1` → `space1`.
String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

Map<String, dynamic> _map(Map<String, dynamic> json, String key) =>
    json[key] as Map<String, dynamic>? ??
    (throw FormatException('missing "$key"'));

List<dynamic> _list(Map<String, dynamic> json, String key) =>
    json[key] as List<dynamic>? ?? (throw FormatException('missing "$key"'));
